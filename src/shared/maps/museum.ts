const CELL = 50;
const SIZE = MUSEUM.size;
type Box = { x: number; y: number; w: number; h: number };
/** Cell corners (inclusive) to a pixel rect. */
const cells = (c0: number, r0: number, c1: number, r1: number): Box => ({ x: c0 * CELL, y: r0 * CELL, w: (c1 - c0 + 1) * CELL, h: (r1 - r0 + 1) * CELL });
const turnBox = (b: Box): Box => ({ x: SIZE - b.x - b.w, y: SIZE - b.y - b.h, w: b.w, h: b.h });
const withTurns = <T>(west: readonly T[], turn: (t: T) => T): T[] => [...west, ...west.map(turn)];

export type MuseumFloorKind = 'marble' | 'parquet' | 'carpet' | 'tile' | 'vault' | 'sand' | 'treasury' | 'slate' | 'concrete' | 'terrazzo' | 'ice' | 'space' | 'ocean' | 'lab' | 'kids' | 'dock';
export type DistrictId = 'egypt' | 'gems' | 'treasury' | 'armour' | 'impress' | 'modern' | 'sculpt' | 'shop' | 'cafe' | 'iceage' | 'space' | 'oceans' | 'lab' | 'kids' | 'dock' | 'entrance' | 'gemhall' | 'giants' | 'nhall' | 'shall' | 'rotunda' | 'grounds';
export type MuseumFloor = Box & { kind: MuseumFloorKind };
export type MuseumExit = { x: number; y: number; vertical: boolean };
export type MuseumBeam = { x1: number; y1: number; x2: number; y2: number; dead?: true };
export type District = Box & { id: DistrictId; name: string; floor: MuseumFloorKind | null; inset: boolean; /** Wash over the floor and the colour of its lights. */ wash: string; light: string };
export type MuseumSign = { text: string; x: number; y: number; vertical?: boolean; small?: true };

const D = (id: DistrictId, name: string, r: Box, floor: MuseumFloorKind | null, inset: boolean, wash: string, light: string): District => ({ id, name, ...r, floor, inset, wash, light });

